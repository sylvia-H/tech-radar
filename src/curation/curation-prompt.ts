import { MAX_ITEMS } from './curation-quota';
import { CurationItemView } from './curation.types';

/**
 * 組出送給 LlmService 的每日單次策展 prompt：候選逐行編號呈現（含 `onBoard` 標記，
 * 使榜單相關性脈絡實際進入 prompt，FR-001）；明列「重要 ≠ 熱門」優先類別、主題降噪優先序
 * （FR-004 語意判斷交此次呼叫執行）、配額、繁中 70/500、殘留語意去重，並限定回應格式
 * （research D1、contracts/llm-response.schema.md）。
 *
 * 「重要性判準」錨點（2026-08-04 新增）：實測發現候選池變大時（同一 `seenNews` 基準下從 35→41
 * 則），LLM 會刷掉候選池較小時原本收錄、且客觀上仍符合「重大模型／API 發布」的候選（如某次
 * DeepMind 新模型公告），只因同批候選變多、相對排序被稀釋——策展本無跨日記憶，每次都是全新
 * 一次判斷，若只給相對式指示（「依重要性排序」）沒有絕對判準，門檻會隨候選池組成漂移。加入
 * 具體「算/不算重大」的判定情境與「候選池大小不改變同一則內容是否重要」的明示，讓 LLM 對每則
 * 候選各自核對固定判準，而非跟同批其他候選比較著選，藉此壓低這種 batch composition 效應造成
 * 的誤刪（憲章 V 限定新聞策展每日僅呼叫 Gemini 一次，故只能在單次 prompt 內用錨點緩解，
 * 不能靠多次呼叫分批評估）。
 *
 * 【官方發布】優先於【社群熱度】的收錄順序（2026-08-04 新增）：把「社群熱度也算重大」納入
 * 判準後（見上），實測候選池含大量高分 HN 討論串時，會反過來把同一批候選池裡原本會收錄的
 * 【官方發布】候選（如 cpython/gemini-robotics-er-2 這類版本/模型發布）擠掉，總則數雖從 6 則
 * 升到 9 則，但官方技術事實類全數被高分熱度文取代——因為 AI 領域則數無上限，兩種都「合格」
 * 時完全看 LLM 當次怎麼分配，沒有機制保護官方事實不被熱度話題排擠。
 *
 * 一開始曾嘗試只用 prompt 敘述指示（「先窮盡評估官方發布、社群熱度只補剩餘名額」）解決，
 * 但實測發現**無效**：total 遠低於 ${MAX_ITEMS}（如 8 則）、官方候選明明還沒選完，LLM 仍會在
 * 同一次生成裡納入多則社群熱度候選——單次生成整個回應的 LLM 沒有真的「先做完一組再做下一組」
 * 這種程序性執行，純文字的順序指示只是軟約束，實測會被違反。2026-08-04 改為**結構性**保證：
 * 回應拆成 `officialPicks`／`communityPicks` 兩個獨立陣列，讓 LLM 只需要把每則候選正確分類到
 * 對的陣列（一個遠比「記得執行順序」簡單的任務），「官方優先」則交給 `curation-validate.ts`
 * 合併時固定把 `officialPicks` 排在 `communityPicks` 之前來保證——即使 LLM 在各陣列內部的判斷
 * 不完美，只要分類正確，官方發布就不會被截斷在社群熱度之後。
 *
 * 發表天齡（2026-09-02 新增）：投影原本沒有任何時間資訊，LLM 分不出三週前與今天的文章；配合
 * `seenNews` 保留期改為 45 天後，候選池裡合法存在最多 30 天的舊文，需要讓 LLM 在「重要性相當」
 * 時偏好較新者。沿用絕對判準錨點的寫法，明示天齡不改變是否重大，避免 LLM 把新鮮度當硬規則
 * 刷掉重要舊聞、或反過來因為新就收錄不重要的內容。
 */
export function buildCurationPrompt(items: readonly CurationItemView[]): string {
  const lines = items
    .map((it) => {
      const boardMark = it.onBoard ? '★在榜 ' : '';
      const scoreLabel = it.score !== null ? `分數 ${it.score}` : '分數 無';
      const ageLabel = it.ageDays !== null ? `${it.ageDays} 天前` : '日期不明';
      return `[${it.ref}] ${boardMark}(${it.domain}/tier${it.tier}/${scoreLabel}/${it.sourceCount} 來源/${ageLabel}) ${it.title}${
        it.summaryExcerpt ? `\n    摘要：${it.summaryExcerpt}` : ''
      }`;
    })
    .join('\n');

  return `你是技術雷達的每日新聞策展人。以下是今天的候選新聞清單（已去重、已排序），請完成三件事：
(a) 認出候選中「不同連結但其實是同一件事」的殘留語意重複，只保留其中一則；
(b) 依「對開發者的重要性」（非熱度）挑出最多 ${MAX_ITEMS} 則——優先會改變開發者做事方式的內容
    （新工具／框架／版本、breaking change、安全通報、重大模型／API 發布、標準變動、重大 deprecation），
    壓低純爆紅口水／drama／純觀點文；分數僅為提示、非排序主鍵；
(c) 把每則精煉為繁體中文標題（≤70 字）＋內容（≤500 字，說清「發生什麼事＋為何對開發者重要」）。

重要性判準是絕對的，與今天候選池大小無關：請針對每一則候選各自核對是否命中以下任一類型，
不要跟同批其他候選比較「誰比較特別」再決定去留——候選池今天特別多或特別少，都不改變同一則
內容本身是否重要：
- 算重大、應收錄：
  (1)【官方發布】官方發布新模型／新工具／新版本或重大能力更新（即使只是一篇官方 blog 宣布、
      沒有大篇幅報導也算數）、breaking change、安全通報、標準變動、重大 deprecation。
  (2)【社群熱度】來自 Hacker News / Lobste.rs / Reddit 等高信度社群、分數或討論熱度異常高的
      任何形式內容（包括觀點文、評論、討論串）——社群熱度本身就是「開發者關注度」的訊號，
      反映現在業界在熱烈討論什麼、思想風向如何。
- 不算重大、不應收錄：
  - 純活動／系列文預告或開場導言（無具體技術內容）、純社群統計／公關類報告
  - 低分數或無分數來源（RSS/Release/論文摘錄）的純觀點文或個人想法
  - CSS 教學
不要因為候選池今天特別多，就覺得某則內容「感覺沒那麼特別」而不選；也不要因為候選池特別少，
就放寬標準硬湊數量。

新鮮度：每則候選標示發表天齡（「N 天前」）。重要性相當時優先較新者；但天齡不改變一則內容
是否重大——只要命中上述判準，即使發表已數週仍應收錄，不得只因較舊就刷掉；也不得只因較新
就收錄不重要的內容。

【官方發布】的技術事實不該被【社群熱度】文章擠掉名額——社群討論會隨話題退燒而失去參考價值，
官方發布是穩定的事實紀錄。因此輸出時把兩者分開放進兩個陣列（見下方輸出規則），程式端會保證
\`officialPicks\` 一律優先於 \`communityPicks\`。你只需要誠實把合格候選分別放進對的陣列、依重要性
排序，不用自己計算「該不該現在放社群熱度」——不要因為想著要幫社群熱度留名額，就先不收錄某則
其實合格的官方發布；也不要為了不讓 \`officialPicks\` 太長，就把明明是官方發布的候選硬塞進
\`communityPicks\`。

主題降噪（選擇非 AI 候選時的優先序，DevOps 優先於後端／前端）：
- DevOps／基礎設施：優先考慮。
- 後端：只看 Node.js／Python 相關；其他語言生態系降低優先。
- 前端：以 TypeScript 為主；Vue／React 相關優先度最低；CSS 技巧／教學一律不選。

配額（無強制則數目標，實際能收錄幾則交由程式依當日 AI／非AI 供給狀況動態決定，你不需要自我設限）：
- AI 與 DevOps／後端／前端皆不設固定則數上限：逐一評估每則「是否真的重要」，凡合格皆收錄；
  不要因為已經湊到「感覺還可以」的數量就提早停手，也不要為了衝數量硬選不重要的內容。
- 全部類別合計最多 ${MAX_ITEMS} 則（程式端硬性把關；非 AI 依比例通常遠少於 AI，但實際比例由
  程式依當日 AI 供給狀況決定，你只需要誠實選出每個類別裡真正重要的候選）。

候選清單（\`[ref]\` 為索引，回應時只需回 ref，不要覆述標題）：
${lines || '（無候選）'}

候選標記說明：「★在榜」表示該候選提到目前榜上的 repo，可作為重要性判斷的正面提示（非唯一依據）。

輸出規則：
- 只回傳單一 JSON 物件，分成兩個陣列：
  {"officialPicks":[{"ref":<候選索引>,"title":"<繁中標題,≤70字>","content":"<繁中內容,≤500字>"}],
   "communityPicks":[{"ref":<候選索引>,"title":"<繁中標題,≤70字>","content":"<繁中內容,≤500字>"}]}
- 【官方發布】類的候選放進 \`officialPicks\`；【社群熱度】類的候選放進 \`communityPicks\`；沒有
  的類別回空陣列 \`[]\`，兩個鍵都必須存在。
- 各陣列內部的順序即你判斷的重要性由高到低排序；兩陣列合計最多 ${MAX_ITEMS} 則。
- 不得回傳連結、分數、星數、名次，也不得回傳候選清單中不存在的 ref。
- 候選不足或無合適候選時，該陣列可回傳較少則數甚至空陣列，不得為了湊數選入不重要的內容。
- 不要輸出 JSON 以外的文字或說明。`;
}
